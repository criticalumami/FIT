def ics_escape(text):
    return str(text).replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n")


def session_description(item, data, program):
    desc = [item.get("rx", ""), item.get("dur", "")]
    if item.get("type", "").upper().startswith("RR"):
        active = data.get("activeProgressions", {})
        desc.append("")
        desc.append("Current steps:")
        for ex in program["exercises"]:
            if ex["category"] in ("pair1", "pair2", "pair3", "core"):
                step = active.get(ex["id"]) or ex["ladders"][0]
                desc.append(f"- {ex['slot']}: {step} ({ex['targetRange']})")
    return "\n".join(d for d in desc if d is not None)


def calendar_events(data, program, start, weeks):
    """Yield (date, title, description) for each scheduled day."""
    start = start - timedelta(days=start.weekday())  # align to Monday
    for w in range(weeks):
        for item in data.get("schedule") or program["defaultSchedule"]:
            offset = DAY_INDEX.get(item["day"].upper()[:3])
            if offset is None:
                continue
            yield start + timedelta(days=w * 7 + offset), f"FIT: {item['type']}", session_description(item, data, program)


def ics_fold(line):
    """RFC 5545: lines longer than 75 octets continue on the next line after a space."""
    raw = line.encode("utf-8")
    if len(raw) <= 75:
        return line
    parts, chunk = [], b""
    for ch in line:
        b = ch.encode("utf-8")
        if len(chunk) + len(b) > (75 if not parts else 74):
            parts.append(chunk.decode("utf-8"))
            chunk = b""
        chunk += b
    parts.append(chunk.decode("utf-8"))
    return "\r\n ".join(parts)


def build_ics(events):
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//FIT//Training Schedule//EN", "CALSCALE:GREGORIAN"]
    for d, title, desc in events:
        out += [
            "BEGIN:VEVENT",
            # Stable UID per day so re-importing updates events instead of duplicating them.
            f"UID:fit-{d.isoformat()}@fit.local",
            f"DTSTAMP:{stamp}",
            f"DTSTART;VALUE=DATE:{d.strftime('%Y%m%d')}",
            f"DTEND;VALUE=DATE:{(d + timedelta(days=1)).strftime('%Y%m%d')}",
            f"SUMMARY:{ics_escape(title)}",
            f"DESCRIPTION:{ics_escape(desc)}",
            "END:VEVENT",
        ]
    out.append("END:VCALENDAR")
    return "\r\n".join(ics_fold(l) for l in out) + "\r\n"


def push_apple_calendar(events, start):
    """Replace all 'FIT:' events from `start` onward in the macOS Calendar 'FIT' calendar."""
    def q(text):
        return text.replace("\\", "\\\\").replace('"', '\\"')

    # Dates are built from numeric parts: AppleScript date strings depend on the system locale.
    lines = [
        'on mkdate(y, m, d)',
        '  set t to current date',
        '  set day of t to 1',
        '  set year of t to y',
        '  set month of t to m',
        '  set day of t to d',
        '  set time of t to 0',
        '  return t',
        'end mkdate',
        'tell application "Calendar"',
        '  if not (exists calendar "FIT") then make new calendar with properties {name:"FIT"}',
        '  tell calendar "FIT"',
        f'    set cutoff to my mkdate({start.year}, {start.month}, {start.day})',
        '    try',
        '      delete (every event whose summary begins with "FIT:" and start date ≥ cutoff)',
        '    end try',
    ]
    for d, title, desc in events:
        lines += [
            f'    set sDate to my mkdate({d.year}, {d.month}, {d.day})',
            f'    make new event at end with properties {{summary:"{q(title)}", start date:sDate, end date:sDate, allday event:true, description:"{q(desc)}"}}',
        ]
    lines += ["  end tell", "end tell"]
    res = subprocess.run(["osascript", "-e", "\n".join(lines)], capture_output=True, text=True)
    if res.returncode != 0:
        sys.exit(f"osascript failed: {res.stderr.strip()}")
    print("updated macOS Calendar 'FIT'")


# ---------------------------------------------------------------- PROGRAM.md blocks

def schedule_md(data, program):
    rows = ["| Day | Session | Prescription | Duration / Intensity |", "| :--- | :--- | :--- | :--- |"]
    for s in data.get("schedule") or program["defaultSchedule"]:
        rows.append(f"| **{md_cell(s['day'])}** | {md_cell(s['type'])} | {md_cell(s['rx'])} | {md_cell(s['dur'])} |")
    return "\n".join(rows)


LEVEL_PREFIX = re.compile(r"^L[0-9]+:\s*")


def ladders_md(program):
    titles = {"pair1": "Pair 1", "pair2": "Pair 2", "pair3": "Pair 3", "core": "Core Triplet", "skill": "Sunday Skills"}
    out = []
    for ex in program["exercises"]:
        rule = (f"{ex['minRep']}–{ex['maxRep']} reps: below {ex['minRep']} → easier step; "
                f"{ex['maxRep']},{ex['maxRep']},{ex['maxRep']} → next step") if ex.get("maxRep") else "extend hold time / quality"
        out.append(f"#### {ex['slot']} — `{ex['targetRange']}` ({rule})")
        out.extend(f"{i}. {LEVEL_PREFIX.sub('', step)}" for i, step in enumerate(ex["ladders"], 1))
        out.append("")
        out.append("*Cues:* " + " ".join(ex["cues"]))
        out.append("")
        out.append(f"*Avoid:* {ex['faults']}")
        out.append("")
    return "\n".join(out).rstrip()


def replace_block(text, name, body):
    pat = re.compile(rf"(<!-- BEGIN GENERATED:{name} -->).*?(<!-- END GENERATED:{name} -->)", re.S)
    if not pat.search(text):
        raise ValueError(f"PROGRAM.md is missing the GENERATED:{name} markers")
    return pat.sub(lambda m: f"{m.group(1)}\n{body}\n{m.group(2)}", text)


# ---------------------------------------------------------------- commands

def cmd_generate(args):
    data, program = load_data(), load_program()
    write(os.path.join(OUT_DIR, "WORKOUT_LOG.md"), workout_log_md(data))
    write(os.path.join(OUT_DIR, "rr_log.csv"), rr_csv(data))

    start = date.fromisoformat(args.start or data.get("meta", {}).get("programStart") or date.today().isoformat())
    events = list(calendar_events(data, program, start, args.weeks))
    write(os.path.join(OUT_DIR, "fit_schedule.ics"), build_ics(events))

    if os.path.exists(PROGRAM_MD):
        text = open(PROGRAM_MD, encoding="utf-8").read()
        new = replace_block(replace_block(text, "schedule", schedule_md(data, program)), "ladders", ladders_md(program))
        if new != text:
            write(PROGRAM_MD, new)

    if args.copy_to:
        dest = os.path.expanduser(args.copy_to)
        shutil.copy(os.path.join(OUT_DIR, "WORKOUT_LOG.md"), os.path.join(dest, "FIT - Workout Log (generated).md"))
        print(f"copied WORKOUT_LOG.md -> {dest}")
    if args.apple_calendar:
        push_apple_calendar(events, events[0][0] if events else start)


def new_id(prefix):
    return f"{prefix}-{int(datetime.now(timezone.utc).timestamp() * 1000)}"


def cmd_log_weight(args):
    auto_sync(args, "before")
    data = load_data()
    data.setdefault("weightLog", []).append(
        {"id": new_id("w"), "date": args.date, "kg": args.kg, "kcal": None, "updatedAt": now_iso()})
    save_data(data)
    print(f"logged {args.kg} kg on {args.date}")
    auto_sync(args, "after")


def cmd_log_run(args):
    auto_sync(args, "before")
    data = load_data()
    data.setdefault("runLog", []).append({
        "id": new_id("r"), "date": args.date, "type": args.type,
        "km": args.km, "min": args.min, "hr": args.hr, "maxHr": args.max_hr, "notes": args.notes or "",
        "updatedAt": now_iso(),
    })
    for field in ("power", "kcal", "vo2"):
        if getattr(args, field) is not None:
            data["runLog"][-1][field] = getattr(args, field)
    save_data(data)
    print(f"logged {args.km} km run on {args.date}")
    auto_sync(args, "after")


def cmd_log_rr(args):
    auto_sync(args, "before")
    data = load_data()
    active = data.get("activeProgressions", {})
    weights = sorted(data.get("weightLog", []), key=lambda w: w["date"])
    entry = {"id": f"rr-{args.date}", "date": args.date, "bw": args.bw or (weights[-1]["kg"] if weights else None)}
    sets = dict(kv.split("=", 1) for kv in args.sets)
    unknown = set(sets) - {k for _, k in RR_SLOTS} - {"antiext", "antirot", "ext"}
    if unknown:
        sys.exit(f"unknown keys: {', '.join(sorted(unknown))}")
    for _, k in RR_SLOTS:
        entry[f"{k}_prog"] = active.get(k, "")
        entry[f"{k}_sets"] = sets.get(k, "")
    for k in ("antiext", "antirot", "ext"):
        entry[k] = sets.get(k, "")
    entry["notes"] = args.notes or ""
    entry["updatedAt"] = now_iso()
    data.setdefault("rrSessions", [])
    data["rrSessions"] = [s for s in data["rrSessions"] if s.get("id") != entry["id"]] + [entry]
    save_data(data)
    print(f"logged RR session {args.date}")
    auto_sync(args, "after")


# Apple Health export ------------------------------------------------------

HK = "HKQuantityTypeIdentifier"
SUM_TYPES = {HK + t for t in ("StepCount", "DistanceWalkingRunning", "ActiveEnergyBurned", "BasalEnergyBurned",
                              "FlightsClimbed", "AppleExerciseTime")}
POINT_TYPES = {HK + t for t in ("BodyMass", "BodyFatPercentage", "LeanBodyMass", "WaistCircumference",
                                "RestingHeartRate", "WalkingHeartRateAverage", "VO2Max", "HeartRateVariabilitySDNN")}


def parse_health(xml_path, since):
    """Single streaming pass over Export.xml. Personal characteristics (<Me>) are deliberately skipped."""
    counts = Counter()
    daily = defaultdict(lambda: defaultdict(lambda: defaultdict(float)))  # day -> type -> source -> sum
    points = defaultdict(lambda: defaultdict(dict))  # type -> source -> day -> value (last wins)
    sleep = defaultdict(float)
    activity = {}
    workouts = []
    for _, el in ET.iterparse(xml_path, events=("end",)):
        tag = el.tag
        if tag == "Record":
            a = el.attrib
            rtype, sdate = a.get("type", ""), a.get("startDate", "")
            counts[rtype] += 1
            if sdate >= since:
                day = sdate[:10]
                try:
                    if rtype in SUM_TYPES:
                        daily[day][rtype][a.get("sourceName", "")] += float(a.get("value", ""))
                    elif rtype in POINT_TYPES:
                        points[rtype][a.get("sourceName", "")][day] = float(a.get("value", ""))
                except ValueError:
                    pass
                if rtype == "HKCategoryTypeIdentifierSleepAnalysis" and "Asleep" in a.get("value", ""):
                    try:
                        t1 = datetime.strptime(sdate[:19], "%Y-%m-%d %H:%M:%S")
                        t2 = datetime.strptime(a["endDate"][:19], "%Y-%m-%d %H:%M:%S")
                        sleep[a["endDate"][:10]] += (t2 - t1).total_seconds() / 3600
                    except (KeyError, ValueError):
                        pass
            el.clear()
        elif tag == "Workout":
            if el.attrib.get("startDate", "") >= since:
                w = dict(el.attrib)
                w["stats"] = {c.attrib.get("type", ""): c.attrib for c in el if c.tag == "WorkoutStatistics"}
                workouts.append(w)
            el.clear()
        elif tag == "ActivitySummary":
            dc = el.attrib.get("dateComponents", "")
            if dc >= since:
                activity[dc] = dict(el.attrib)
            el.clear()
    # VO2 Max is estimated by both phone and watch; the watch's post-run value is the one that
    # matters, so prefer the sources that record workouts. Other metrics merge all sources.
    workout_sources = {w.get("sourceName") for w in workouts}
    merged = {}
    for t, by_src in points.items():
        srcs = [s for s in by_src if s in workout_sources] if t == HK + "VO2Max" else []
        merged[t] = {}
        for src in (srcs or list(by_src)):
            merged[t].update(by_src[src])
    points = merged
    return {"counts": counts, "daily": daily, "points": points, "sleep": sleep, "activity": activity, "workouts": workouts}


def best_source(by_src):
    """Watch and phone both record steps/energy; take the larger source rather than summing (no double count)."""
    return max(by_src.values()) if by_src else 0.0


def daily_breakdown_txt(h):
    days = sorted(set(h["daily"]) | set(h["activity"]))
    p = h["points"]
    head = f"{'Date':10} | {'Wt':5} | {'ActKcal':7} | {'Basal':5} | {'TDEE':5} | {'ExMin':5} | {'Steps':6} | {'Km':5} | {'RHR':4} | {'WHR':4} | {'VO2':5} | {'Sleep':5}"
    out = [head, "-" * len(head)]
    for d in days:
        dd = h["daily"].get(d, {})
        act = h["activity"].get(d)
        act_kcal = float(act.get("activeEnergyBurned", 0)) if act else best_source(dd.get(HK + "ActiveEnergyBurned", {}))
        ex_min = float(act.get("appleExerciseTime", 0)) if act else best_source(dd.get(HK + "AppleExerciseTime", {}))
        basal = best_source(dd.get(HK + "BasalEnergyBurned", {}))
        steps = best_source(dd.get(HK + "StepCount", {}))
        km = best_source(dd.get(HK + "DistanceWalkingRunning", {}))

        def pt(t, f="{:.0f}"):
            v = p.get(HK + t, {}).get(d)
            return f.format(v) if v is not None else ""
        slp = f"{h['sleep'][d]:.1f}" if d in h["sleep"] else ""
        out.append(f"{d:10} | {pt('BodyMass', '{:.1f}'):5} | {act_kcal:7.0f} | {basal:5.0f} | {act_kcal + basal:5.0f} | {ex_min:5.0f} | "
                   f"{steps:6.0f} | {km:5.1f} | {pt('RestingHeartRate'):4} | {pt('WalkingHeartRateAverage'):4} | {pt('VO2Max', '{:.1f}'):5} | {slp:5}")
    return "\n".join(out) + "\n"


def health_summary_txt(h):
    out = ["=== RECORD COUNTS ==="]
    out += [f"{t}: {n}" for t, n in h["counts"].most_common()]
    out.append("\n=== POINT METRICS (last 15) ===")
    for t, by_day in sorted(h["points"].items()):
        out.append(f"\n--- {t.replace(HK, '')} ---")
        out += [f"  {d}: {v}" for d, v in sorted(by_day.items())[-15:]]
    out.append(f"\n=== WORKOUTS (last 20 of {len(h['workouts'])}) ===")
    for w in sorted(h["workouts"], key=lambda w: w.get("startDate", ""))[-20:]:
        out.append(f"  {w.get('startDate')} | {w.get('workoutActivityType', '').replace('HKWorkoutActivityType', '')} | "
                   f"{float(w.get('duration', 0) or 0):.1f} {w.get('durationUnit', '')}")
    return "\n".join(out) + "\n"


# Private data repo sync (same repo and merge rules as the web app) ----------

LOG_KEYS = ("rrSessions", "weightLog", "runLog", "dailyLog")


def now_iso():
    """Same format as JS new Date().toISOString(), so timestamps compare as strings."""
    t = datetime.now(timezone.utc)
    return t.strftime("%Y-%m-%dT%H:%M:%S.") + f"{t.microsecond // 1000:03d}Z"


def merge_states(local, remote):
    """Mirror of lib.js mergeStates(); keep the two identical (tests/fixtures check both)."""
    import copy
    if remote is None:
        return copy.deepcopy(local)
    if local is None:
        return copy.deepcopy(remote)

    def newer(a, b):
        return str(b or "") > str(a or "")

    def count(s):
        return sum(len(s.get(k) or []) for k in LOG_KEYS)

    lt, rt = str(local.get("settingsUpdatedAt") or ""), str(remote.get("settingsUpdatedAt") or "")
    # Later settings win; on a tie, a side with no log entries (fresh/empty browser) never wins.
    base = remote if rt > lt or (rt == lt and count(local) == 0 and count(remote) > 0) else local
    out = copy.deepcopy(base)
    deleted = {**(remote.get("deleted") or {}), **(local.get("deleted") or {})}
    for i, t in (remote.get("deleted") or {}).items():
        if newer(deleted[i], t):
            deleted[i] = t
    out["deleted"] = deleted
    for key in LOG_KEYS:
        by_id = {}
        for e in local.get(key) or []:
            by_id[e["id"]] = e
        for e in remote.get(key) or []:
            cur = by_id.get(e["id"])
            if cur is None or newer(cur.get("updatedAt"), e.get("updatedAt")):
                by_id[e["id"]] = e
        kept = [copy.deepcopy(e) for e in by_id.values()
                if e["id"] not in deleted or newer(deleted[e["id"]], e.get("updatedAt"))]
        out[key] = sorted(kept, key=lambda e: (str(e.get("date")), str(e.get("id"))))
    return out


def stable(obj):
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def gh_api(*args, input_text=None):
    res = subprocess.run(["gh", "api", *args], input=input_text, capture_output=True, text=True)
    if res.returncode != 0:
        err = RuntimeError(res.stderr.strip() or res.stdout.strip())
        err.conflict = "409" in err.args[0] or "422" in err.args[0]
        raise err
    return res.stdout


def assert_private(repo):
    if json.loads(gh_api(f"repos/{repo}")).get("private") is not True:
        sys.exit(f"Refusing to sync: {repo} is not private.")


def get_remote(repo, path):
    """Returns (text, sha), or (None, None) if the file doesn't exist."""
    import base64
    try:
        meta = json.loads(gh_api(f"repos/{repo}/contents/{path}"))
    except RuntimeError as e:
        if "404" in str(e) or "Not Found" in str(e):
            return None, None
        raise
    return base64.b64decode(meta["content"]).decode("utf-8"), meta["sha"]


def put_remote(repo, path, text, sha, message):
    import base64
    body = {"message": message, "content": base64.b64encode(text.encode("utf-8")).decode("ascii")}
    if sha:
        body["sha"] = sha
    gh_api("-X", "PUT", f"repos/{repo}/contents/{path}", "--input", "-", input_text=json.dumps(body))


def sync(repo, quiet=False):
    """Merge local data.json with the repo copy both ways. Returns True on success."""
    assert_private(repo)
    for attempt in range(3):
        text, sha = get_remote(repo, "data.json")
        remote = json.loads(text) if text else None
        local = load_data() if os.path.exists(DATA_PATH) else None
        merged = merge_states(local, remote)
        if local is None or stable(merged) != stable(local):
            save_data(merged)
        if remote is not None and stable(merged) == stable(remote):
            break
        try:
            put_remote(repo, "data.json", json.dumps(merged, indent=2, ensure_ascii=False) + "\n", sha, "Sync from fit.py")
        except RuntimeError as e:
            if getattr(e, "conflict", False) and attempt < 2:
                continue  # someone pushed in between: re-read and merge again
            raise
        _, log_sha = get_remote(repo, "WORKOUT_LOG.md")
        put_remote(repo, "WORKOUT_LOG.md", workout_log_md(merged), log_sha, "Sync WORKOUT_LOG.md from fit.py")
        break
    if not quiet:
        print(f"in sync with {repo}")
    return True


def auto_sync(args, when):
    """Best-effort sync around log-* commands; never blocks logging when offline."""
    if getattr(args, "offline", False) or shutil.which("gh") is None:
        return
    try:
        sync(args.repo, quiet=True)
    except (RuntimeError, OSError) as e:
        print(f"warning: sync {when} logging failed ({str(e).splitlines()[0][:120]}); run `python3 fit.py sync` later",
              file=sys.stderr)


def cmd_sync(args):
    sync(args.repo)


def cmd_pull(args):
    """Replace local data.json with the repo copy (recovery). Normal use: `sync`."""
    assert_private(args.repo)
    text, _ = get_remote(args.repo, "data.json")
    if text is None:
        sys.exit(f"{args.repo} has no data.json")
    if os.path.exists(DATA_PATH):
        shutil.copy(DATA_PATH, DATA_PATH + ".bak")
    save_data(json.loads(text))
    print(f"replaced data.json with {args.repo}'s copy (previous copy saved as data.json.bak)")


# Apple Health -> data.json -------------------------------------------------
# Both sources produce the same normalized "health day": full exports
# (`import-health`) and the iPhone Shortcut (inbox/*.json in the data repo,
# merged by its GitHub Action via `ingest-inbox`). Imports are idempotent.

def _num(v, integer=False):
    """Number from Shortcuts text in any locale -> float, else None.

    '78,9 kg' -> 78.9, '29.376 Schritte' -> 29376 (integer field), '12 345' -> 12345,
    '1,234.5' -> 1234.5. `integer` marks fields that are never fractional (steps,
    kcal, bpm), so a lone '.'/',' followed by exactly three digits is a thousands
    separator there, and a decimal separator elsewhere.
    """
    if v is None or v == "" or isinstance(v, bool):
        return None
    if isinstance(v, (int, float)):
        return float(v)
    m = re.search(r"-?\d[\d.,'\s\u00a0\u202f]*", str(v))
    if not m:
        return None
    t = re.sub(r"[\s\u00a0\u202f']", "", m.group(0)).rstrip(".,")
    if "," in t and "." in t:  # the later separator is the decimal one
        t = t.replace(".", "").replace(",", ".") if t.rfind(",") > t.rfind(".") else t.replace(",", "")
    elif "," in t or "." in t:
        sep = "," if "," in t else "."
        if integer and re.fullmatch(r"-?\d{1,3}(?:" + re.escape(sep) + r"\d{3})+", t):
            t = t.replace(sep, "")
        else:
            t = t.replace(",", ".")
    try:
        return float(t)
    except ValueError:
        return None


DAY_FIELDS = ("weightKg", "restingHr", "steps", "activeKcal", "sleepH", "vo2")
INTEGER_FIELDS = {"restingHr", "steps", "activeKcal", "hr", "maxHr", "power", "kcal"}
DAILY_FIELDS = ("restingHr", "steps", "activeKcal", "sleepH", "vo2")


def normalize_health_day(p):
    date = str(p.get("date") or "")[:10]
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", date):
        raise ValueError(f"bad or missing date: {p.get('date')!r}")
    day = {"date": date, "runs": []}
    for key in DAY_FIELDS:
        v = _num(p.get(key), key in INTEGER_FIELDS)
        if v is not None and v > 0:
            day[key] = v
    raw = p.get("runs") or []
    if isinstance(raw, str):  # Shortcut text form: one "km|minutes[|kcal]" per line
        raw = [line for line in raw.splitlines() if line.strip()]
    for r in raw:
        if isinstance(r, str):
            parts = [x.strip() for x in r.split("|")]
            r = dict(zip(("km", "min", "kcal"), parts))
        km, mins = _num(r.get("km")), _num(r.get("min"))
        if mins is None and _num(r.get("sec")):
            mins = _num(r.get("sec")) / 60
        if not km or not mins:
            continue
        if km > 100:  # metres
            km /= 1000
        if mins > 400:  # seconds
            mins /= 60
        run = {"km": round(km, 2), "min": round(mins, 1)}
        for k in ("hr", "maxHr", "power", "kcal"):
            v = _num(r.get(k), integer=True)
            if v:
                run[k] = round(v)
        day["runs"].append(run)
    return day


def classify_run(r):
    hr = r.get("hr")
    if r["km"] >= 9.5:
        return "Long Aerobic Run"
    if hr and hr <= 148:
        return "Easy Run (Zone 2)"
    if hr and hr >= 155:
        return "Tempo / Threshold Run"
    return "Aerobic Run"


def apply_health_day(data, day, now=None):
    """Merge one normalized health day into data. Returns a list of change descriptions."""
    now = now or now_iso()
    d = day["date"]
    changes = []
    for k in LOG_KEYS:
        data.setdefault(k, [])
    deleted = data.get("deleted") or {}

    def upsert(key, entry, fields):
        cur = next((e for e in data[key] if e.get("id") == entry["id"]), None)
        if cur is None:
            if entry["id"] in deleted:  # deleted by the user: don't bring it back
                return
            entry["updatedAt"] = now
            data[key].append(entry)
            changes.append(f"+ {key} {d}")
            return
        diff = {f: entry[f] for f in fields if f in entry and cur.get(f) != entry[f]}
        if diff:
            cur.update(diff)
            cur["updatedAt"] = now
            changes.append(f"~ {key} {d} {sorted(diff)}")

    # Weight: a weigh-in the user logged by hand that day always wins.
    if "weightKg" in day and not any(
            w.get("date") == d and not str(w.get("id")).startswith("w-hk-") for w in data["weightLog"]):
        upsert("weightLog", {"id": f"w-hk-{d}", "date": d, "kg": round(day["weightKg"], 1), "kcal": None,
                             "source": "Apple Health"}, ["kg"])

    daily = {k: day[k] for k in DAILY_FIELDS if k in day}
    if daily:
        entry = {"id": f"d-{d}", "date": d}
        entry.update({k: (round(v, 1) if k in ("sleepH", "vo2") else int(round(v))) for k, v in daily.items()})
        upsert("dailyLog", entry, list(daily))

    for r in day["runs"]:
        same = [x for x in data["runLog"] if x.get("date") == d and abs(float(x.get("km") or 0) - r["km"]) < 0.3]
        if any(not str(x.get("id")).startswith("r-hk-") for x in same):
            continue  # already logged by hand
        rid = same[0]["id"] if same else f"r-hk-{d}-{int(round(r['km'] * 100))}"
        entry = {"id": rid, "date": d, "type": classify_run(r), "km": r["km"], "min": r["min"],
                 "notes": "Imported from Apple Health"}
        entry.update({k: r[k] for k in ("hr", "maxHr", "power", "kcal") if k in r})
        upsert("runLog", entry, ["km", "min", "hr", "maxHr", "power", "kcal"])
    return changes


def health_days_from_export(path, since):
    """Normalized health days from a full Export.xml or the export .zip."""
    import zipfile
    if path.lower().endswith(".zip"):
        with zipfile.ZipFile(path) as zf:
            name = next(n for n in zf.namelist() if n.endswith("/Export.xml") or n == "Export.xml")
            with zf.open(name) as fh:
                h = parse_health(fh, since)
    else:
        h = parse_health(path, since)
    p = h["points"]
    days = {}
    for d in sorted(set(h["daily"]) | set(h["activity"]) | set(h["sleep"])):
        dd = h["daily"].get(d, {})
        act = h["activity"].get(d)
        raw = {
            "date": d,
            "weightKg": p.get(HK + "BodyMass", {}).get(d),
            "restingHr": p.get(HK + "RestingHeartRate", {}).get(d),
            "vo2": p.get(HK + "VO2Max", {}).get(d),
            "steps": best_source(dd.get(HK + "StepCount", {})) or None,
            "activeKcal": float(act["activeEnergyBurned"]) if act and act.get("activeEnergyBurned")
            else best_source(dd.get(HK + "ActiveEnergyBurned", {})) or None,
            "sleepH": h["sleep"].get(d),
            "runs": [],
        }
        days[d] = raw
    for w in h["workouts"]:
        if w.get("workoutActivityType") != "HKWorkoutActivityTypeRunning":
            continue
        d = w.get("startDate", "")[:10]
        st = {k.replace(HK, ""): v for k, v in w["stats"].items()}
        g = lambda t, k: (st.get(t) or {}).get(k)  # noqa: E731
        days.setdefault(d, {"date": d, "runs": []})["runs"].append({
            "km": g("DistanceWalkingRunning", "sum"), "min": w.get("duration"),
            "hr": g("HeartRate", "average"), "maxHr": g("HeartRate", "maximum"),
            "power": g("RunningPower", "average"), "kcal": g("ActiveEnergyBurned", "sum"),
        })
    return [normalize_health_day(days[d]) for d in sorted(days)]


def cmd_import_health(args):
    auto_sync(args, "before")
    data = load_data()
    changes = []
    for day in health_days_from_export(os.path.expanduser(args.export), args.since):
        changes += apply_health_day(data, day)
    if changes:
        save_data(data)
    print(f"{len(changes)} change(s) from Apple Health since {args.since}")
    for c in changes:
        print("  " + c)
    auto_sync(args, "after")


def cmd_ingest_inbox(args):
    """Merge inbox/*.json (from the iPhone Shortcut) into data.json; used by the data repo's Action."""
    global DATA_PATH
    DATA_PATH = os.path.abspath(args.data)
    data = load_data()
    changes, done = [], []
    failed_dir = os.path.join(args.inbox, "failed")
    for name in sorted(os.listdir(args.inbox)):
        path = os.path.join(args.inbox, name)
        if not name.endswith(".json") or not os.path.isfile(path):
            continue
        try:
            with open(path, encoding="utf-8") as f:
                payload = json.load(f)
            for p in payload if isinstance(payload, list) else [payload]:
                changes += apply_health_day(data, normalize_health_day(p))
            os.remove(path)
            done.append(name)
        except (ValueError, KeyError, TypeError) as e:
            os.makedirs(failed_dir, exist_ok=True)
            os.replace(path, os.path.join(failed_dir, name))
            print(f"rejected {name}: {e}", file=sys.stderr)
    if changes:
        save_data(data)
        if args.log:
            with open(args.log, "w", encoding="utf-8") as f:
                f.write(workout_log_md(data))
    print(f"ingested {len(done)} file(s), {len(changes)} change(s)")
    for c in changes:
        print("  " + c)


